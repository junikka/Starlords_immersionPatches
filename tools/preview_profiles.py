"""Preview faction wording profiles without launching the game.

    python tools/preview_profiles.py

Writes docs/immersion-audit/generated/profile_preview.md: every message a profile may
override (data/lords/presentation/overridable_keys.json), as each bound faction and the
default profile see it. Resolution matches Java's ProfileRegistry: the faction's profile,
then each profile it extends, then neutral.json. A cell is marked "=" when that faction
uses the default wording. Re-run after editing profiles.json or neutral.json.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PRESENTATION = ROOT / 'data/lords/presentation'
OUTPUT = ROOT / 'docs/immersion-audit/generated/profile_preview.md'


def load(name):
    return json.loads((PRESENTATION / name).read_text(encoding='utf-8'))


def resolver():
    """Returns (keys, factions, resolve) where resolve(faction, key) is the wording that faction sees."""
    messages = load('neutral.json')['messages']
    keys = load('overridable_keys.json')['keys']
    profiles = load('profiles.json')

    def chain(faction):
        name, seen = profiles['factions'].get(faction, 'default'), []
        while name != 'default':
            if name in seen:
                raise SystemExit('Profile inheritance cycle: %s' % seen)
            seen.append(name)
            name = profiles['profiles'][name].get('extends', 'default')
        return seen

    def resolve(faction, key):
        for name in chain(faction):
            value = profiles['profiles'][name].get('messages', {}).get(key)
            if value is not None:
                return value
        return messages[key]

    return keys, list(profiles['factions']), resolve


def cell(text):
    return '`' + text.replace('|', '¦').replace('`', "'") + '`'


def main():
    keys, factions, resolve = resolver()
    profiles = load('profiles.json')['factions']
    lines = ['# Faction wording preview', '',
             'Generated by `tools/preview_profiles.py` from `profiles.json`; do not edit. '
             '`=` means the faction uses the default wording. `¦` separates tooltip lines.', '',
             '| Message | default | ' + ' | '.join('%s (%s)' % (f, profiles[f]) for f in factions) + ' |',
             '|---' * (len(factions) + 2) + '|']
    for key in keys:
        default = resolve(None, key)
        row = [cell(key), cell(default)]
        for faction in factions:
            value = resolve(faction, key)
            row.append('=' if value == default else cell(value))
        lines.append('| ' + ' | '.join(row) + ' |')
    OUTPUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('Wrote %s (%d messages x %d factions)' % (OUTPUT.relative_to(ROOT), len(keys), len(factions)))


if __name__ == '__main__':
    main()
